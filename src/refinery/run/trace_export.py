"""Export an event log as a TLA+ trace module for ``spec/Run.tla`` (D7).

The module replays the log against Run's own actions. TLC accepts the log as
a behaviour of Run iff it reports ``TraceIncomplete`` violated; a rejected log
deadlocks. The text is pinned by golden files that were checked with TLC.
"""

from collections.abc import Sequence
from dataclasses import dataclass

from refinery.run.model import Action, Event


@dataclass(frozen=True)
class TraceModule:
    """A generated ``Trace_<run>.tla`` and its ``.cfg``."""

    name: str
    tla: str
    cfg: str


# Everything after the trace itself is the same for every run. Doubled braces
# are literal TLA+ braces in str.format.
_TLA = """\
---- MODULE {name} ----
\\* Generated by refinery.run.trace_export from the event log of run
\\* {run_id}. Do not edit. TLC accepts the log as a behaviour of Run
\\* iff it reports TraceIncomplete violated.
EXTENDS Run

TheRun == CHOOSE r \\in Runs : TRUE
TheChange == CHOOSE c \\in Changes : TRUE

Trace == <<
{rows}
>>

VARIABLE i  \\* trace events consumed so far

TraceInit == Init /\\ i = 0

Step(act) ==
{arms}

\\* An Archive attempt is in flight but was never logged: its validation
\\* failed and the event was withdrawn.
Withdrawn == Len(log[TheRun]) > i

\\* Event i+1 is begun by its action and must match the logged event; then
\\* CommitRecord finishes it (Archive first needs a passing CheckTrace).
\\* A withdrawn Archive attempt is replayed only where the log shows one,
\\* right before RetryArchive, and must end in AbortArchive. Each choice is
\\* forced, so TLC's verdict does not depend on search order.
TraceNext ==
    \\/ /\\ i < Len(Trace)
       /\\ Step(Trace[i + 1].act)
       /\\ log'[TheRun][Len(log'[TheRun])] = Trace[i + 1]
       /\\ i' = i + 1
    \\/ /\\ i < Len(Trace)
       /\\ Trace[i + 1].act = "RetryArchive"
       /\\ Archive(TheRun)
       /\\ UNCHANGED i
    \\/ /\\ CheckTrace(TheRun)
       /\\ pending'[TheRun][1].verdict = IF Withdrawn THEN "fail" ELSE "pass"
       /\\ UNCHANGED i
    \\/ AbortArchive(TheRun) /\\ UNCHANGED i
    \\/ CommitRecord(TheRun) /\\ ~Withdrawn /\\ UNCHANGED i

\\* Accepted: every event consumed, nothing in flight, and the run is where
\\* the last event left it.
TraceIncomplete ==
    ~(/\\ i = Len(Trace)
      /\\ pending[TheRun] = <<>>
      /\\ log[TheRun] = Trace
      /\\ phase[TheRun] = Trace[Len(Trace)].to)
========
"""

_CFG = """\
\\* Generated by refinery.run.trace_export for run {run_id}. Do not edit.
CONSTANTS
    Runs = {{r1}}
    Changes = {{c1}}
    NoChange = NoChange
    MaxLog = {count}

INIT TraceInit
NEXT TraceNext
INVARIANT TraceIncomplete
"""


def module_name(run_id: str) -> str:
    """A TLA+ module name for ``run_id`` (TLA+ identifiers allow no - or .)."""
    return "Trace_" + "".join(c if c.isalnum() else "_" for c in run_id)


def _arms() -> str:
    """Step's CASE: every action of Run, called on the single modelled run."""
    lines: list[str] = []
    for index, action in enumerate(Action):
        args = "TheRun, TheChange" if action is Action.START_RUN else "TheRun"
        lead = "    CASE" if index == 0 else "      []"
        lines.append(f'{lead} act = "{action.value}" -> {action.value}({args})')
    return "\n".join(lines)


def export_trace(run_id: str, events: Sequence[Event]) -> TraceModule:
    """TLC accepts ``events`` iff it reports ``TraceIncomplete`` violated."""
    if not events:
        raise ValueError("an empty log has no trace to export")
    rows = ",\n".join(
        f'    [act |-> "{e.name.value}", from |-> "{e.from_phase.value}", '
        f'to |-> "{e.to_phase.value}"]'
        for e in events
    )
    name = module_name(run_id)
    return TraceModule(
        name=name,
        tla=_TLA.format(name=name, run_id=run_id, rows=rows, arms=_arms()),
        cfg=_CFG.format(run_id=run_id, count=len(events)),
    )
